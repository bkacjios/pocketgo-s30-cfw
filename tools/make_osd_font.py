#!/usr/bin/env python3
"""Make utils/osd_font.h: printable ASCII (0x20-0x7e) of the kernel's VGA
8x16 console font (lib/fonts/font_8x16.c, GPL-2.0, from the kernel tree)
for s30-display's menu text.

Usage: python3 tools/make_osd_font.py [font_8x16.c]
"""
import re
import sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
FONT = Path(sys.argv[1]) if len(sys.argv) > 1 else PROJECT / "external" / "linux" / "lib" / "fonts" / "font_8x16.c"
GLYPH_H = 16

rows = [int(b, 16) for b in re.findall(r"^\s*(0x[0-9a-fA-F]{2}),", FONT.read_text(), re.M)]
assert len(rows) == 256 * GLYPH_H, f"{FONT}: {len(rows)} rows, expected {256 * GLYPH_H}"

out = ["/* Generated by tools/make_osd_font.py from the kernel's lib/fonts/font_8x16.c",
       "   (VGA 8x16 console font, GPL-2.0): ASCII 0x20-0x7e, one byte per row,",
       "   bit 7 leftmost. */",
       "static const unsigned char kOsdFont[95][16] = {"]
for ch in range(0x20, 0x7F):
    glyph = ", ".join(f"0x{b:02x}" for b in rows[ch * GLYPH_H:(ch + 1) * GLYPH_H])
    out.append(f"\t{{ {glyph} }}, // '{chr(ch)}'" if ch != 0x5C else f"\t{{ {glyph} }}, // backslash")
out.append("};")
(PROJECT / "utils" / "osd_font.h").write_text("\n".join(out) + "\n")
